# bake the torso's new texture coordinates from the final Studio export (recv/torso_final.txt):
# per-vertex uv for every vertex + per-face overrides where a face needs its own corners; writes the Luau patch and a check image
import sys, numpy as np
from uvfix2 import face_uv
from render import render_uv, checker, grid

SEAM = 0.035
def load(path):
    d = {}
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            k, _, rest = line.rstrip("\n").partition(" ")
            d[k] = rest
    vec = lambda s: np.array([[float(x) for x in t.split()] for t in s.split(";")])
    out = {k: vec(d[k]) for k in ("base", "nbase", "uv", "P0", "P1", "P2")}
    out["tris"] = np.array([int(x) for x in d["tris"].split()]).reshape(-1, 3)
    out["cap"] = np.array([int(x) for x in d["capids"].split()])
    return out

def seam_fix(c):
    # MuscleRig.faceUVs' rule: a corner far from the other two (another shirt panel) takes their middle
    a, b, cc = c
    dab, dbc, dca = np.linalg.norm(a - b), np.linalg.norm(b - cc), np.linalg.norm(cc - a)
    if max(dab, dbc, dca) <= SEAM: return c
    if min(dab, dbc, dca) > SEAM: return np.array([a, a, a])
    if dab <= dbc and dab <= dca: return np.array([a, b, (a + b) / 2])
    if dbc <= dca: return np.array([(b + cc) / 2, b, cc])
    return np.array([a, (cc + a) / 2, cc])

m = load(sys.argv[1])
base, tris = m["base"], m["tris"]
fuv, cls, F, suv = face_uv(base, m["uv"], tris, m["cap"], m["P1"])
# the seam rule only where the OLD layout crossed a panel seam (the re-meshed cap's big triangles are legit)
capset = np.zeros(len(base), bool); capset[m["cap"]] = True
olduv = m["uv"][tris]
crosses = np.array([not capset[t].any() and max(np.linalg.norm(o[0] - o[1]), np.linalg.norm(o[1] - o[2]), np.linalg.norm(o[2] - o[0])) > SEAM for t, o in zip(tris, olduv)])
fuv = np.array([seam_fix(c) if x else c for c, x in zip(fuv, crosses)])
n = len(base)
# per vertex: the value most of its corners have
votes = {}
for k, t in enumerate(tris):
    for j, v in enumerate(t):
        key = (round(fuv[k, j, 0], 5), round(fuv[k, j, 1], 5))
        votes.setdefault(v, {}); votes[v][key] = votes[v].get(key, 0) + 1
vuv = suv.copy()
for v, vs in votes.items(): vuv[v] = max(vs.items(), key=lambda kv: kv[1])[0]
# faces whose corners differ from the per-vertex values, or that the seam rule would change, keep their own corners
over = []
for k, t in enumerate(tris):
    if np.abs(fuv[k] - vuv[t]).max() > 2e-5 or np.abs(seam_fix(vuv[t]) - vuv[t]).max() > 1e-9:
        over.append(k)
print("faces with own corners", len(over), "of", len(tris), "| classes", {c: cls.count(c) for c in "FBLR"})

# Studio keeps a script under 200,000 characters: the main module (sys.argv[2]) + parts <main>_1.. beside it
uvs = [",".join("%.5f,%.5f" % (u, v) for u, v in vuv[i:i + 8000]) for i in range(0, n, 8000)]
fcs = [",".join("%d,%s" % (k, ",".join("%.5f" % x for x in fuv[k].ravel())) for k in over[i:i + 1500]) for i in range(0, len(over), 1500)]
parts = [("uv", t) for t in uvs] + [("faces", t) for t in fcs]
stem = sys.argv[2][:-len(".luau")]
NL = chr(10)
for i, (key, text) in enumerate(parts, 1):
    with open("%s_%d.luau" % (stem, i), "w", encoding="utf-8", newline=NL) as fh:
        fh.write("return { %s = {%s} }" % (key, text) + NL)
main = [
    "-- generated by tools/torso_patches/torso_uv_patch.py: the torso's texture coordinates (see MuscleMeshes applyUVPatch); the",
    "-- lists are in the modules <this name>_1 .. _%d beside it (a script holds under 200,000 characters)" % len(parts),
    "local out = { verts = %d, triCount = %d, uv = {}, faces = {} }" % (n, len(tris)),
    "for i = 1, %d do" % len(parts),
    "\tfor key, list in pairs(require(script.Parent:WaitForChild(script.Name .. \"_\" .. i))) do",
    "\t\ttable.move(list, 1, #list, #out[key] + 1, out[key])",
    "\tend",
    "end",
    "return out",
]
with open(sys.argv[2], "w", encoding="utf-8", newline=NL) as fh: fh.write(NL.join(main) + NL)

# check image: the checker on the old and new layout, front / back, at the full look and the mass monster
old = np.array([seam_fix(c) for c in m["uv"][tris]])
tex = checker()
ims = []
for P in (m["P1"], m["P2"]):
    for f in (old, fuv):
        for yaw in (0, 180):
            ims.append(render_uv(P, tris, f, yaw=yaw, pitch=20, size=360, scale=170, center=(0, 0.45), tex=tex))
grid(ims, 4, sys.argv[3])
